def cmp(a, b):
    return S.compare(a, b)


def ci(r):
    return f"{r['ci_items'][0]:+.1f} to {r['ci_items'][1]:+.1f}"


def pfmt(p):
    return f"{p:.3g}"


def h(t):
    print(f"\n## {t}\n")


def table(head, rows):
    print("| " + " | ".join(head) + " |")
    print("|" + "|".join("---" for _ in head) + "|")
    for r in rows:
        print("| " + " | ".join(str(x) for x in r) + " |")
    print()


